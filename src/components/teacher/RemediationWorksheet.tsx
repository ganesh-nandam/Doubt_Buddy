import { useState, useMemo } from 'react';
import { FileText, Sparkles, Download, X, Printer, FileDown } from 'lucide-react';
import { students, practiceQuestionBank } from '@/data';
import type { WorksheetQuestion, WeakSpot } from '@/types';

const difficultyConfig = {
  easy: { color: 'text-brand-600', bg: 'bg-brand-50', border: 'border-brand-200' },
  medium: { color: 'text-accent-600', bg: 'bg-accent-50', border: 'border-accent-200' },
  hard: { color: 'text-coral-600', bg: 'bg-coral-50/50', border: 'border-coral-200' },
};

interface AggregatedWeakSpot extends WeakSpot {
  studentsAffected: string[];
  avgMastery: number;
}

/**
 * Scans all students' weak spots, aggregates by topic, and returns
 * the top 3 topics with the lowest average mastery.
 */
function compileTopWeakSpots(): AggregatedWeakSpot[] {
  const topicMap = new Map<string, AggregatedWeakSpot>();

  for (const student of students) {
    for (const spot of student.weakSpots) {
      const existing = topicMap.get(spot.topic);
      if (existing) {
        existing.studentsAffected.push(student.name);
        existing.avgMastery = Math.round(
          (existing.avgMastery * (existing.studentsAffected.length - 1) + spot.mastery) /
          existing.studentsAffected.length
        );
        existing.attempts += spot.attempts;
      } else {
        topicMap.set(spot.topic, {
          ...spot,
          id: `agg-${spot.topic}`,
          studentsAffected: [student.name],
          avgMastery: spot.mastery,
        });
      }
    }
  }

  return Array.from(topicMap.values())
    .sort((a, b) => a.avgMastery - b.avgMastery)
    .slice(0, 3);
}

/**
 * Builds worksheet questions for the given weak spots using the
 * practice question bank. Picks difficulty based on average mastery.
 */
function buildQuestions(weakSpots: AggregatedWeakSpot[]): WorksheetQuestion[] {
  const questions: WorksheetQuestion[] = [];
  const seen = new Set<string>();

  for (const spot of weakSpots) {
    const bank = practiceQuestionBank[spot.topic];
    if (!bank) continue;

    const difficulty = spot.avgMastery < 40 ? 'easy' : spot.avgMastery < 60 ? 'medium' : 'hard';
    const q = bank[difficulty];
    if (q && !seen.has(q.id)) {
      questions.push({
        id: q.id,
        topic: q.topic,
        difficulty,
        question: q.question,
        answer: q.answer,
      });
      seen.add(q.id);
    }
  }

  return questions;
}

/**
 * Generates a clean, printable text summary of the worksheet.
 */
function generateTextSummary(
  weakSpots: AggregatedWeakSpot[],
  questions: WorksheetQuestion[]
): string {
  const date = new Date().toLocaleDateString('en-US', {
    weekday: 'long',
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  });

  let text = '';
  text += '═══════════════════════════════════════════════════════\n';
  text += '              DOUBT-BUDDY REMEDIATION WORKSHEET\n';
  text += '═══════════════════════════════════════════════════════\n';
  text += `\n  Class:     10-B  ·  Mathematics & Physics\n`;
  text += `  Date:      ${date}\n`;
  text += `  Generated: Auto-compiled from student weak-spot data\n`;
  text += '\n───────────────────────────────────────────────────────\n';
  text += '  TARGETED WEAK SPOTS (Top 3)\n';
  text += '───────────────────────────────────────────────────────\n\n';

  weakSpots.forEach((spot, i) => {
    text += `  ${i + 1}. ${spot.topic}  (${spot.subject})\n`;
    text += `     Average Mastery: ${spot.avgMastery}%\n`;
    text += `     Students Affected: ${spot.studentsAffected.join(', ')}\n`;
    text += `     Difficulty Level: ${spot.avgMastery < 40 ? 'Easy' : spot.avgMastery < 60 ? 'Medium' : 'Hard'}\n\n`;
  });

  text += '───────────────────────────────────────────────────────\n';
  text += '  PRACTICE QUESTIONS\n';
  text += '───────────────────────────────────────────────────────\n\n';

  questions.forEach((q, i) => {
    text += `  Q${i + 1}. [${q.difficulty.toUpperCase()}]  (${q.topic})\n`;
    text += `      ${q.question}\n`;
    text += `      ______________________________________________\n`;
    text += `      ______________________________________________\n\n`;
  });

  text += '───────────────────────────────────────────────────────\n';
  text += '  ANSWER KEY (For Teacher Use)\n';
  text += '───────────────────────────────────────────────────────\n\n';

  questions.forEach((q, i) => {
    text += `  ${i + 1}. ${q.answer}\n`;
  });

  text += '\n═══════════════════════════════════════════════════════\n';
  text += '  Generated by DOUBT-BUDDY  ·  doubt-buddy.app\n';
  text += '═══════════════════════════════════════════════════════\n';

  return text;
}

export function RemediationWorksheet() {
  const [showWorksheet, setShowWorksheet] = useState(false);
  const [weakSpots, setWeakSpots] = useState<AggregatedWeakSpot[]>([]);
  const [questions, setQuestions] = useState<WorksheetQuestion[]>([]);

  // Pre-compute affected student count for the CTA card
  const affectedStudents = useMemo(() => {
    const top3 = compileTopWeakSpots();
    const names = new Set<string>();
    top3.forEach((spot) => spot.studentsAffected.forEach((n) => names.add(n)));
    return names.size;
  }, []);

  const handleGenerate = () => {
    const topWeak = compileTopWeakSpots();
    const wsQuestions = buildQuestions(topWeak);
    setWeakSpots(topWeak);
    setQuestions(wsQuestions);
    setShowWorksheet(true);
  };

  const handleDownload = () => {
    const summary = generateTextSummary(weakSpots, questions);
    const blob = new Blob([summary], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `remediation-worksheet-${new Date().toISOString().split('T')[0]}.txt`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  const handlePrint = () => {
    const summary = generateTextSummary(weakSpots, questions);
    const printWindow = window.open('', '_blank', 'width=800,height=600');
    if (!printWindow) return;
    printWindow.document.write(`
      <html>
        <head>
          <title>DOUBT-BUDDY Remediation Worksheet</title>
          <style>
            body {
              font-family: 'Courier New', monospace;
              max-width: 700px;
              margin: 40px auto;
              padding: 20px;
              color: #1f2530;
              line-height: 1.6;
            }
            pre {
              font-size: 13px;
              white-space: pre-wrap;
              word-wrap: break-word;
            }
            @media print {
              body { margin: 20px; }
            }
          </style>
        </head>
        <body>
          <pre>${summary.replace(/</g, '&lt;').replace(/>/g, '&gt;')}</pre>
        </body>
      </html>
    `);
    printWindow.document.close();
    printWindow.focus();
    setTimeout(() => printWindow.print(), 300);
  };

  return (
    <>
      {/* CTA Button */}
      <div className="relative overflow-hidden rounded-3xl bg-gradient-to-br from-accent-500 via-accent-600 to-accent-700 p-6 shadow-lift">
        <div className="absolute -right-8 -top-8 h-32 w-32 rounded-full bg-white/10" />
        <div className="absolute -right-12 -bottom-12 h-40 w-40 rounded-full bg-white/5" />

        <div className="relative flex flex-col items-start gap-4 sm:flex-row sm:items-center sm:justify-between">
          <div>
            <div className="mb-2 flex items-center gap-2">
              <FileText className="text-white" size={22} />
              <h3 className="font-display text-xl font-bold text-white">Remediation Worksheet</h3>
            </div>
            <p className="text-sm text-white/80">
              Auto-compile the top 3 class weak spots into a printable handout.{' '}
              <span className="font-semibold text-white">{affectedStudents} students</span> need remediation.
            </p>
          </div>

          <button
            onClick={handleGenerate}
            className="flex items-center gap-2 rounded-xl bg-white px-5 py-3 text-sm font-bold text-accent-600 shadow-lg transition-all hover:shadow-xl hover:scale-105 active:scale-95"
          >
            <Sparkles size={18} />
            Generate Now
          </button>
        </div>
      </div>

      {/* Worksheet Modal */}
      {showWorksheet && (
        <div
          className="fixed inset-0 z-50 flex items-center justify-center bg-ink-950/60 backdrop-blur-sm animate-fade-in p-4"
          onClick={() => setShowWorksheet(false)}
        >
          <div
            className="max-h-[85vh] w-full max-w-2xl overflow-y-auto scrollbar-thin rounded-3xl bg-white shadow-lift animate-fade-in-up"
            onClick={(e) => e.stopPropagation()}
          >
            {/* Header */}
            <div className="sticky top-0 z-10 flex items-center justify-between border-b border-ink-100 bg-white px-6 py-4">
              <div>
                <h3 className="font-display text-lg font-bold text-ink-900">
                  Remediation Worksheet
                </h3>
                <p className="text-xs text-ink-500">
                  {weakSpots.length} targeted topics · {questions.length} questions · {affectedStudents} students
                </p>
              </div>
              <div className="flex items-center gap-2">
                <button
                  onClick={handleDownload}
                  className="flex items-center gap-1.5 rounded-lg border border-ink-200 px-3 py-1.5 text-xs font-semibold text-ink-600 transition-all hover:bg-ink-50"
                >
                  <FileDown size={14} />
                  Download
                </button>
                <button
                  onClick={handlePrint}
                  className="flex items-center gap-1.5 rounded-lg border border-ink-200 px-3 py-1.5 text-xs font-semibold text-ink-600 transition-all hover:bg-ink-50"
                >
                  <Printer size={14} />
                  Print
                </button>
                <button
                  onClick={() => setShowWorksheet(false)}
                  className="flex h-8 w-8 items-center justify-center rounded-lg text-ink-400 transition-all hover:bg-ink-50 hover:text-ink-600"
                >
                  <X size={18} />
                </button>
              </div>
            </div>

            {/* Worksheet content */}
            <div className="space-y-5 px-6 py-5">
              {/* Targeted weak spots summary */}
              <div className="rounded-2xl bg-brand-50 p-4">
                <h4 className="mb-3 text-sm font-bold text-brand-700">Targeted Weak Spots</h4>
                <div className="space-y-3">
                  {weakSpots.map((spot, idx) => (
                    <div key={spot.id} className="flex items-start gap-3">
                      <span className="flex h-6 w-6 shrink-0 items-center justify-center rounded-lg bg-brand-500 text-xs font-bold text-white">
                        {idx + 1}
                      </span>
                      <div className="flex-1">
                        <div className="flex items-center gap-2">
                          <span className="text-sm font-semibold text-ink-800">{spot.topic}</span>
                          <span className="rounded-md bg-ink-100 px-1.5 py-0.5 text-[10px] font-medium text-ink-500">
                            {spot.subject}
                          </span>
                        </div>
                        <div className="mt-1 flex items-center gap-3">
                          <div className="flex items-center gap-1.5">
                            <div className="h-1.5 w-20 overflow-hidden rounded-full bg-ink-200">
                              <div
                                className={`h-full rounded-full ${
                                  spot.avgMastery < 40 ? 'bg-coral-500' : 'bg-accent-500'
                                } transition-all duration-700`}
                                style={{ width: `${spot.avgMastery}%` }}
                              />
                            </div>
                            <span className="text-xs font-bold text-ink-700">{spot.avgMastery}%</span>
                          </div>
                          <span className="text-[10px] text-ink-400">
                            {spot.studentsAffected.length} students
                          </span>
                        </div>
                      </div>
                    </div>
                  ))}
                </div>
              </div>

              {/* Questions */}
              <div>
                <h4 className="mb-3 text-sm font-bold text-ink-700">Practice Questions</h4>
                <div className="space-y-3">
                  {questions.map((q, idx) => {
                    const cfg = difficultyConfig[q.difficulty];
                    return (
                      <div
                        key={q.id}
                        className="rounded-2xl border border-ink-100 p-4 transition-all hover:border-ink-200 animate-fade-in-up"
                        style={{ animationDelay: `${idx * 60}ms` }}
                      >
                        <div className="flex items-start gap-3">
                          <span className="flex h-7 w-7 shrink-0 items-center justify-center rounded-lg bg-ink-900 text-xs font-bold text-white">
                            {idx + 1}
                          </span>
                          <div className="flex-1">
                            <div className="mb-1.5 flex items-center gap-2">
                              <span className={`rounded-md ${cfg.bg} ${cfg.border} border px-2 py-0.5 text-[10px] font-bold ${cfg.color} uppercase`}>
                                {q.difficulty}
                              </span>
                              <span className="text-[10px] font-medium text-ink-400">{q.topic}</span>
                            </div>
                            <p className="text-sm font-medium text-ink-800">{q.question}</p>
                            {/* Answer lines for print */}
                            <div className="mt-3 hidden border-b border-ink-200 pb-1 print:block">
                              <span className="text-xs text-ink-300">Answer: ____________________________________________</span>
                            </div>
                          </div>
                        </div>
                      </div>
                    );
                  })}
                </div>
              </div>

              {/* Answer Key */}
              <div className="rounded-2xl bg-ink-50 p-4 print:hidden">
                <h4 className="mb-3 text-sm font-bold text-ink-700">Answer Key</h4>
                <div className="grid grid-cols-1 gap-2 sm:grid-cols-2">
                  {questions.map((q, idx) => (
                    <div key={q.id} className="flex items-center gap-2 text-xs">
                      <span className="flex h-5 w-5 items-center justify-center rounded-md bg-ink-200 text-[10px] font-bold text-ink-600">
                        {idx + 1}
                      </span>
                      <span className="font-medium text-ink-700">{q.answer}</span>
                    </div>
                  ))}
                </div>
              </div>
            </div>
          </div>
        </div>
      )}
    </>
  );
}
